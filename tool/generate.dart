// Writes the generated tables from shared/data and checks the patro data against the hub's
// shared/spec/vectors/patro-summary.json. Run from the repository root:
//
//   dart run tool/generate.dart           write the files
//   dart run tool/generate.dart --check   exit 1 if a file on disk differs from what would be written
//
// The library never reads JSON at run time; it only imports the files this tool writes.

import 'dart:convert';
import 'dart:io';

const _minYear = 1901;
const _maxYear = 2199;
const _years = _maxYear - _minYear + 1;
const _months = _years * 12;
const _maxSerial = 109211;
const _header = '// Generated by tool/generate.dart from shared/data. Do not edit.\n';

const _calendarOut = 'packages/nepdate/lib/src/calendar.g.dart';
const _patroOut = 'packages/nepdate_patro/lib/src/tables.g.dart';

Never _fail(String message) {
  stderr.writeln('generate: $message');
  exit(1);
}

Map<String, Object?> _readJson(String path) {
  try {
    return jsonDecode(File(path).readAsStringSync()) as Map<String, Object?>;
  } on Object catch (error) {
    _fail('cannot read $path: $error');
  }
}

/// Days since 1970-01-01 of a proleptic Gregorian date (ALGORITHM section 5).
int _daysFromCivil(int year, int month, int day) {
  final y = month <= 2 ? year - 1 : year;
  final era = y ~/ 400;
  final yoe = y - era * 400;
  final mp = (month + 9) % 12;
  final doy = (153 * mp + 2) ~/ 5 + day - 1;
  final doe = yoe * 365 + yoe ~/ 4 - yoe ~/ 100 + doy;
  return era * 146097 + doe - 719468;
}

/// Serial of the first day of every month, then the total as the last entry.
List<int> _readMonthStarts() {
  final json = _readJson('shared/data/calendar/bs-calendar.json');
  if (json['min_year'] != _minYear || json['max_year'] != _maxYear) {
    _fail('expected years $_minYear..$_maxYear, got ${json['min_year']}..${json['max_year']}');
  }
  final lengths = json['month_lengths']! as Map<String, Object?>;
  if (lengths.length != _years) _fail('month_lengths has years outside the range');
  final starts = <int>[];
  var serial = 0;
  for (var year = _minYear; year <= _maxYear; year++) {
    final row = lengths['$year'];
    if (row is! List<Object?> || row.length != 12) _fail('year $year must have 12 month lengths');
    for (final length in row) {
      if (length is! int || length < 29 || length > 32) {
        _fail('year $year has month length $length, expected 29..32');
      }
      starts.add(serial);
      serial += length;
    }
  }
  starts.add(serial);
  if (serial != _maxSerial + 1) _fail('the table has $serial days, expected ${_maxSerial + 1}');
  return starts;
}

String _intList(String name, List<int> values, String doc) {
  final out = StringBuffer('/// $doc\nconst List<int> $name = [\n');
  var line = StringBuffer('  ');
  for (final value in values) {
    final item = '$value,';
    if (line.length + item.length + 1 > 100) {
      out.writeln(line.toString().trimRight());
      line = StringBuffer('  ');
    }
    line.write('$item ');
  }
  if (line.toString().trim().isNotEmpty) out.writeln(line.toString().trimRight());
  out.writeln('];');
  return out.toString();
}

String _quote(String value) {
  final out = StringBuffer('"');
  for (final unit in value.runes) {
    switch (unit) {
      case 0x22:
        out.write(r'\"');
      case 0x5C:
        out.write(r'\\');
      case 0x24:
        out.write(r'\$');
      case 0x0A:
        out.write(r'\n');
      default:
        out.writeCharCode(unit);
    }
  }
  return (out..write('"')).toString();
}

String _stringList(String name, List<String> values, String doc) {
  final body = values.map((v) => '  ${_quote(v)},\n').join();
  return '/// $doc\nconst List<String> $name = [\n$body];\n';
}

String _calendarSource(List<int> starts) {
  final epoch = _daysFromCivil(1844, 4, 11);
  if (epoch != -45920) _fail('epoch is $epoch, expected -45920');
  return '''$_header
/// The first BS year in the tables.
const int kMinYear = $_minYear;

/// The last BS year in the tables.
const int kMaxYear = $_maxYear;

/// Days from 1970-01-01 to BS 1901-01-01 (AD 1844-04-11).
const int kEpochUnixDays = $epoch;

/// The number of days from BS 1901-01-01 to the end of 2199 (the serial after the last day).
const int kTotalDays = ${starts.last};

${_intList('kMonthStart', starts, 'Serial of the first day of each of the $_months months, then kTotalDays.')}''';
}

class _Named {
  _Named(this.np, this.en);
  final String np;
  final String en;
  String get key => '$np\u0000$en';
}

class _Day {
  _Day(this.serial, this.label, this.tithi, this.holiday, this.events);
  final int serial;
  final String label;
  final _Named? tithi;
  final bool holiday;
  final List<_Named> events;
}

_Named _named(Object? value, String where) {
  if (value is! Map<String, Object?> || value['np'] is! String || value['en'] is! String) {
    _fail('$where must have np and en strings');
  }
  return _Named(value['np']! as String, value['en']! as String);
}

List<_Day> _readDays(List<int> starts) {
  final files = Directory('shared/data/patro')
      .listSync()
      .whereType<File>()
      .where((f) => RegExp(r'[\\/]\d{4}\.json$').hasMatch(f.path))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  if (files.isEmpty) _fail('shared/data/patro has no year files');
  final days = <_Day>[];
  final seen = <int>{};
  for (final file in files) {
    final name = file.uri.pathSegments.last;
    final json = _readJson(file.path);
    if (json['schema'] != 1) _fail('$name: schema ${json['schema']}, expected 1');
    final fileYear = int.parse(name.substring(0, 4));
    if (json['year'] != fileYear) _fail('$name: year ${json['year']} does not match the file name');
    for (final entry in (json['days']! as Map<String, Object?>).entries) {
      final label = entry.key;
      final match = RegExp(r'^(\d{4})-(\d{2})-(\d{2})$').firstMatch(label);
      if (match == null) _fail('$name: date $label is not YYYY-MM-DD');
      final year = int.parse(match.group(1)!);
      final month = int.parse(match.group(2)!);
      final dayOfMonth = int.parse(match.group(3)!);
      if (year != fileYear) _fail('$name: date $label is not in $fileYear');
      if (month < 1 || month > 12) _fail('$name: date $label has month $month');
      final index = (year - _minYear) * 12 + month - 1;
      final length = starts[index + 1] - starts[index];
      if (dayOfMonth < 1 || dayOfMonth > length) {
        _fail('$name: date $label has day $dayOfMonth, month $year-$month has $length');
      }
      final serial = starts[index] + dayOfMonth - 1;
      if (!seen.add(serial)) _fail('$name: duplicate day $label');
      final day = entry.value! as Map<String, Object?>;
      final tithi = day['tithi'] == null ? null : _named(day['tithi'], '$label.tithi');
      final holiday = day['holiday'];
      if (holiday != null && holiday is! bool) _fail('$label.holiday must be a boolean');
      final rawEvents = day['events'];
      if (rawEvents != null && rawEvents is! List<Object?>) _fail('$label.events must be an array');
      final events = <_Named>[
        for (final (i, e) in ((rawEvents as List<Object?>?) ?? const <Object?>[]).indexed)
          _named(e, '$label.events[$i]'),
      ];
      days.add(_Day(serial, label, tithi, holiday == true, events));
    }
  }
  days.sort((a, b) => a.serial.compareTo(b.serial));
  return days;
}

void _expect(String field, Object? summary, Object? data) {
  if (summary != data) _fail('patro-summary $field is $summary, the data has $data');
}

String _patroSource(List<int> starts) {
  final days = _readDays(starts);
  final pool = <String, int>{};
  final namesNp = <String>[];
  final namesEn = <String>[];
  int poolId(_Named named) => pool.putIfAbsent(named.key, () {
        namesNp.add(named.np);
        namesEn.add(named.en);
        return namesNp.length - 1;
      });

  final tithiDays = days.where((d) => d.tithi != null).toList();
  if (tithiDays.isEmpty) _fail('no tithi data');
  final tithiFirst = tithiDays.first.serial;
  final tithiLast = tithiDays.last.serial;
  final tithiIds = List<int>.filled(tithiLast - tithiFirst + 1, -1);
  for (final day in tithiDays) {
    final offset = day.serial - tithiFirst;
    if (tithiIds[offset] != -1) _fail('tithi data repeats the day at serial ${day.serial}');
    tithiIds[offset] = poolId(day.tithi!);
  }
  for (var offset = 0; offset < tithiIds.length; offset++) {
    if (tithiIds[offset] == -1) _fail('tithi data has a gap at serial ${tithiFirst + offset}');
  }

  final holidays = [
    for (final d in days)
      if (d.holiday) d.serial
  ];
  final eventDays = <int>[];
  final eventCounts = <int>[];
  final eventNameIds = <int>[];
  for (final day in days) {
    if (day.events.isEmpty) continue;
    eventDays.add(day.serial);
    eventCounts.add(day.events.length);
    for (final event in day.events) {
      eventNameIds.add(poolId(event));
    }
  }
  if (holidays.isEmpty) _fail('no holidays');
  if (eventDays.isEmpty) _fail('no events');

  final withData = days.where((d) => d.tithi != null || d.holiday || d.events.isNotEmpty).toList();
  final first = withData.first;
  final last = withData.last;
  var nameBytes = 0;
  for (var i = 0; i < namesNp.length; i++) {
    nameBytes += utf8.encode(namesNp[i]).length + utf8.encode(namesEn[i]).length;
  }

  final summary = _readJson('shared/spec/vectors/patro-summary.json');
  _expect('schema', summary['schema'], 1);
  _expect('first_year', summary['first_year'], int.parse(first.label.substring(0, 4)));
  _expect('last_year', summary['last_year'], int.parse(last.label.substring(0, 4)));
  _expect('first_day', summary['first_day'], first.label);
  _expect('last_day', summary['last_day'], last.label);
  _expect('first_serial', summary['first_serial'], first.serial);
  _expect('last_serial', summary['last_serial'], last.serial);
  _expect('days', summary['days'], last.serial - first.serial + 1);
  _expect('tithi_first_day', summary['tithi_first_day'], tithiDays.first.label);
  _expect('tithi_last_day', summary['tithi_last_day'], tithiDays.last.label);
  _expect('tithi_first_serial', summary['tithi_first_serial'], tithiFirst);
  _expect('tithi_days', summary['tithi_days'], tithiIds.length);
  _expect('tithi_names', summary['tithi_names'], tithiIds.toSet().length);
  _expect('holidays', summary['holidays'], holidays.length);
  _expect('event_days', summary['event_days'], eventDays.length);
  _expect('events', summary['events'], eventNameIds.length);
  _expect('event_names', summary['event_names'], eventNameIds.toSet().length);
  _expect('names', summary['names'], namesNp.length);
  _expect('name_bytes', summary['name_bytes'], nameBytes);

  return '''$_header
// PATRO section 3: the tithi ids come first in the name pool, one id per day from kTithiFirst;
// holidays and event days are sorted serials; events keep file order within a day.

/// Serial of ${first.label}, the first day with any data.
const int kCoverageFirst = ${first.serial};

/// Serial of ${last.label}, the last day with any data.
const int kCoverageLast = ${last.serial};

/// Serial of ${tithiDays.first.label}, the first tithi day.
const int kTithiFirst = $tithiFirst;

${_intList('kTithiIds', tithiIds, '${tithiIds.length} tithi name ids, one per day from kTithiFirst.')}
${_intList('kHolidayDays', holidays, '${holidays.length} holiday serials in ascending order.')}
${_intList('kEventDays', eventDays, '${eventDays.length} event-day serials in ascending order.')}
${_intList('kEventCounts', eventCounts, 'The number of events of each day in kEventDays.')}
${_intList('kEventNameIds', eventNameIds, '${eventNameIds.length} name ids, in file order per day.')}
${_stringList('kNamesNp', namesNp, 'The Nepali side of the deduplicated name pool.')}
${_stringList('kNamesEn', namesEn, 'The English side of the name pool, same indices as kNamesNp.')}''';
}

void main(List<String> arguments) {
  final check = arguments.contains('--check');
  final unknown = arguments.where((a) => a != '--check');
  if (unknown.isNotEmpty) _fail('unknown argument ${unknown.first}');
  final starts = _readMonthStarts();
  final outputs = {
    _calendarOut: _calendarSource(starts),
    _patroOut: _patroSource(starts),
  };
  var drift = false;
  for (final MapEntry(key: path, value: source) in outputs.entries) {
    final file = File(path);
    if (check) {
      final current = file.existsSync() ? file.readAsStringSync().replaceAll('\r\n', '\n') : null;
      if (current != source) {
        stderr.writeln('generate: $path is out of date; run dart run tool/generate.dart');
        drift = true;
      }
    } else {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(source);
      stdout.writeln('generate: wrote $path');
    }
  }
  if (drift) exit(1);
  if (check) stdout.writeln('generate: tables match shared/data');
}
